// Copy shared by signed-out and in-notebook email receipt screens.
export function emailNoticeCopy(kind) {
    return kind === 'recovery' ? {
        lead: 'Запрос на восстановление пароля для адреса:',
        instructions: 'Если аккаунт с этой почтой существует, письмо со ссылкой для смены пароля будет отправлено. Проверьте входящие и спам. Ссылку можно открыть на любом устройстве.'
    } : kind === 'unconfirmed' ? {
        lead: 'Подтвердите почту для аккаунта:',
        instructions: 'Откройте ссылку из письма с подтверждением. Проверьте входящие и спам. Ссылку можно открыть на любом устройстве.'
    } : {
        lead: 'Почта для подтверждения аккаунта:',
        instructions: 'Если для этого адреса требуется подтверждение, письмо со ссылкой будет отправлено. Проверьте входящие и спам. Если аккаунт уже подтверждён, вернитесь к входу. Ссылку можно открыть на любом устройстве.'
    };
}

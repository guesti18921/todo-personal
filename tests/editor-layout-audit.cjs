const assert = require('node:assert/strict');
module.exports = async (browser, origin, { seed, cacheKey }) => {
 const context = await browser.newContext({ viewport: { width: 390, height: 844 }, locale: 'ru-RU', serviceWorkers: 'block' });
 await context.route('**/*.supabase.co/**', route => route.abort());
 await context.addInitScript(seed => { for (const [key, value] of seed) localStorage.setItem(key, value); }, seed);
 const page = await context.newPage();
 try {
  await page.goto(origin); await page.locator('#todo-app:not([hidden])').waitFor();
  await page.addScriptTag({ url: origin + '/__audit-axe.js' });
  await page.locator('[data-view="all"]').click(); await page.locator('.mn-add').click();
  assert.equal(await page.locator('#mn-editor-schedule-body').isVisible(), false);
  assert.ok(await page.locator('#mn-text').evaluate(el => el.getBoundingClientRect().height >= 140), 'phone writing area keeps its original height');
  await page.locator('#mn-text').fill('Текст останется после смены размера');
  await page.locator('#mn-text').evaluate(el => { window.layoutField = el; el.focus(); el.setSelectionRange(4, 4); });
  await page.setViewportSize({ width: 390, height: 430 });
  assert.equal(await page.evaluate(() => document.activeElement === window.layoutField && window.layoutField.selectionStart === 4), true, 'keyboard resize preserves the focused field and caret');
  await page.locator('[data-editor-schedule]').click();
  await page.locator('[name="date"]').fill('2099-01-02');
  await page.locator('[name="reminderMode"]').selectOption('custom');
  await page.locator('[name="reminderDate"]').fill('2099-01-01');
  await page.locator('[data-clock="reminderTime"] [data-clock-open]').click();
  await page.locator('.mn-time-dialog [data-clock-part="hour"]').selectOption('17');
  await page.locator('.mn-time-dialog [data-clock-part="minute"]').selectOption('30');
  await page.locator('.mn-time-dialog .mn-primary').click();
  await page.locator('[data-editor-schedule]').click();
  assert.equal(await page.locator('#mn-editor-schedule-body').isVisible(), false);
  await page.locator('[data-save]').click();
  const saved = await page.evaluate(key => JSON.parse(localStorage.getItem(key)).state.todos.home.find(e => e.name === 'Текст останется после смены размера'), cacheKey);
  assert.equal(saved.date, '2099-01-02'); assert.equal(saved.reminder.mode, 'custom'); assert.equal(saved.reminder.time, '17:30');
  await page.locator('[data-view="all"]').click(); await page.locator(`[data-open="${saved.id}"]`).click();
  assert.equal(await page.locator('#mn-editor-schedule-body').isVisible(), true, 'an existing schedule is open by default');
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.locator('[data-editor-width]').waitFor({ state: 'visible' });
  assert.equal(await page.locator('[data-editor-schedule]').isVisible(), false);
  assert.equal(await page.locator('[data-editor-width]').isVisible(), true);
  assert.ok(await page.evaluate(() => document.querySelector('.mn-editor-options').getBoundingClientRect().left > document.querySelector('.mn-editor-writing').getBoundingClientRect().right), 'desktop options sit beside writing');
  await page.locator('#mn-text').evaluate(el => { window.layoutField = el; });
  await page.locator('[data-editor-width]').click();
  assert.equal(await page.evaluate(() => document.querySelector('#mn-text') === window.layoutField), true);
  assert.ok(await page.evaluate(() => document.querySelector('.mn-editor-options').getBoundingClientRect().top > document.querySelector('.mn-editor-writing').getBoundingClientRect().bottom), 'expanding text moves options below without removing them');
  await page.locator('[data-editor-width]').click();
  await page.setViewportSize({ width: 320, height: 640 });
  await page.locator('[data-editor-width]').waitFor({ state: 'hidden' });
  assert.equal(await page.locator('#mn-text').inputValue(), saved.name);
  assert.equal(await page.locator('[name="reminderTime"]').inputValue(), '17:30');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.locator('[data-back]').click(); await page.locator('[data-view="settings"]').click();
  assert.equal(await page.locator('.mn-settings-group').count(), 3);
  assert.equal(await page.locator('.mn-setting:not(.mn-settings-group .mn-setting) [data-sync-open]').isVisible(), true, 'saving stays outside collapsed groups');
  await page.locator('[data-settings-group="preferences"] > summary').click();
  await page.locator('[data-time-format]').selectOption('12');
  assert.equal(await page.locator('[data-settings-group="preferences"]').getAttribute('open'), '', 'changing format retains the open group');
  await page.locator('[data-language]').selectOption('en');
  assert.equal(await page.locator('[data-settings-group="preferences"]').getAttribute('open'), '');
  assert.match(await page.locator('[data-settings-group="preferences"] > summary').innerText(), /Preferences/);
  await page.locator('[data-settings-group="notifications"] > summary').click();
  const before = await page.locator('[data-toggle-reminders]').innerText();
  await page.locator('[data-toggle-reminders]').click();
  assert.equal(await page.locator('[data-settings-group="notifications"]').getAttribute('open'), '');
  assert.notEqual(await page.locator('[data-toggle-reminders]').innerText(), before);
  const violations = await page.evaluate(async () => (await axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa'] } })).violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.target) })));
  assert.deepEqual(violations, [], 'grouped settings remain accessible');
 } finally { await context.close(); }
 console.log('Responsive editor: original phone text area, keyboard caret, hidden-field save, reopened reminder, two columns/full-width, resize and persistent settings groups passed');
};
